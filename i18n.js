// Joriy til
let currentLang = localStorage.getItem('habitgo_lang') || 'uz';

// Tarjima olish
function t(key) {
    return translations[currentLang]?.[key] || translations.uz[key] || key;
}

// Tilni o'zgartirish
function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('habitgo_lang', lang);
    applyTranslations();
    updateLanguageButtons();
    console.log('[i18n] Til:', lang);
}

// Sahifadagi barcha matnlarni tarjima qilish
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = t(key);
        if (translation) {
            el.textContent = translation;
        }
    });

    // Placeholder'lar
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translation = t(key);
        if (translation) {
            el.placeholder = translation;
        }
    });
}

// Til tugmalarini yangilash
function updateLanguageButtons() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === currentLang);
    });
}

// Sahifa yuklanganda
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    updateLanguageButtons();
});